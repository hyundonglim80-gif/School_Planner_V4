// src/lib/helpTopics.ts
//
// 사용 설명서의 내용. 화면(HelpModal)은 이것을 그리기만 한다.
//
// 세 층으로 되어 있다: 기능별 분류(HELP_CATEGORIES) → 세부 기능(topics) →
// 세부 설명(blocks)과 사용 예(examples). 첫 화면은 분류만 보여 준다.
//
// ⚠️ 바꿀 수 있는 값은 글로 적지 않는다.
//    단축키는 환경설정에서 바꿀 수 있고, 이월 기간도 그렇다. 여기에 키 조합이나
//    날 수를 글로 적어 두면 사용자가 값을 바꾼 순간 설명서가 거짓말을 한다(예전에 실제로
//    그랬다). 아래 자리표를 쓰면 그리는 순간의 실제 값으로 바뀐다.
//      {key:scopeDay}   그 기능에 지금 걸려 있는 단축키
//      {lookback}       환경설정 > 이월의 날 수
//    그 밖의 꾸밈
//      **굵게**
//      [[topic-id|보이는 글]]   다른 항목으로 가는 연결
//
// 새 기능을 만들면 여기에도 한 줄 넣는다. 설명서에 없는 기능은 사용자에게는
// 없는 기능이나 마찬가지다.

import type { ShortcutId } from './shortcuts';

export type HelpBlock =
  | { t: 'p'; text: string }
  /** 작은 제목 */
  | { t: 'h'; text: string }
  | { t: 'ul'; items: string[] }
  /** 차례대로 따라 하는 순서 */
  | { t: 'ol'; items: string[] }
  | { t: 'tip'; text: string }
  | { t: 'note'; text: string }
  /** 왼쪽 칸(누르는 것) / 오른쪽 칸(하는 일) 표 */
  | { t: 'table'; head: [string, string]; rows: Array<[string, string]> }
  /** 환경설정의 단축키를 그대로 펼친 표 */
  | { t: 'shortcuts' };

/** 사용 예: 실제로 겪을 만한 일 하나를 처음부터 끝까지 따라 하는 순서 */
export interface HelpExample {
  title: string;
  steps: string[];
}

/** 세부 기능 */
export interface HelpTopic {
  id: string;
  icon: string;
  title: string;
  /** 목록에 한 줄로 보이는 설명 */
  summary: string;
  /** 세부 설명 */
  blocks: HelpBlock[];
  /** 사용 예. 모든 기능에 하나 이상 둔다. */
  examples: HelpExample[];
  /** 함께 보면 좋은 항목 */
  related?: string[];
}

/** 기능별 분류. 설명서 첫 화면에 카드로 보인다. */
export interface HelpCategory {
  id: string;
  icon: string;
  title: string;
  /** 첫 화면 카드에 보이는 한 줄 */
  summary: string;
  topics: HelpTopic[];
}

